export function normalizeSocialHandle(handle: string): string {
  return handle.replace(/^@/, "").replace(/^\//, "");
}

/** Builds an href from a configured handle/page. */
export function socialUrl(platform: string, raw: string): string | null {
  const h = raw.trim();
  if (!h) return null;
  if (h.startsWith("http://") || h.startsWith("https://")) return h;
  switch (platform) {
    case "instagram":
      return `https://instagram.com/${normalizeSocialHandle(h)}`;
    case "facebook":
      return `https://facebook.com/${normalizeSocialHandle(h)}`;
    case "tiktok":
      return `https://tiktok.com/@${normalizeSocialHandle(h)}`;
    case "x":
      return `https://x.com/${normalizeSocialHandle(h)}`;
    case "youtube":
      return `https://youtube.com/@${normalizeSocialHandle(h)}`;
    default:
      return null;
  }
}

const PLATFORM_META: Record<
  string,
  { label: string; Icon: (p: IconProps) => ReactNode }
> = {
  instagram: { label: "Instagram", Icon: InstagramIcon },
  facebook: { label: "Facebook", Icon: FacebookIcon },
  tiktok: { label: "TikTok", Icon: TikTokIcon },
  x: { label: "X (Twitter)", Icon: XIcon },
  youtube: { label: "YouTube", Icon: YouTubeIcon },
};

export function SocialLinks({
  socials,
  className,
  iconClassName,
  dark = false,
}: {
  socials: Record<string, string>;
  className?: string;
  iconClassName?: string;
  dark?: boolean;
}) {
  return (
    <div className={cn("flex flex-wrap items-center gap-2", className)}>
      {Object.entries(PLATFORM_META).map(([key, meta]) => {
        const href = socialUrl(key, socials[key] ?? "");
        if (!href) return null; // only show configured accounts
        const Icon = meta.Icon;
        return (
          <a
            key={key}
            href={href}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={`${meta.label} (opens in new tab)`}
            className={cn(
              "inline-flex h-10 w-10 items-center justify-center rounded-xl transition-colors",
              dark
                ? "bg-white/10 text-white hover:bg-white/20"
                : "bg-navy-50 text-navy-700 hover:bg-crimson-600 hover:text-white"
            )}
          >
            <Icon className={cn("h-5 w-5", iconClassName)} />
          </a>
        );
      })}
    </div>
  );
}

export function WhatsAppChatLink({
  number,
  text,
  children,
  className,
}: {
  number: string;
  text?: string;
  children?: React.ReactNode;
  className?: string;
}) {
  const clean = number.replace(/[^0-9]/g, "");
  const url = `https://wa.me/${clean}${text ? `?text=${encodeURIComponent(text)}` : ""}`;
  if (children) {
    return (
      <Link href={url} target="_blank" rel="noopener noreferrer" className={className}>
        {children}
      </Link>
    );
  }
  return (
    <a
      href={url}
      target="_blank"
      rel="noopener noreferrer"
      className={cn("inline-flex items-center gap-2", className)}
    >
      <WhatsAppIcon className="h-5 w-5" />
      Chat on WhatsApp
    </a>
  );
}
